async def get_daily_quote_unique() -> tuple[int, str]:
    """
    انتخاب جمله کافه‌ای بدون تکرار نسبت به روزهای اخیر.
    تاریخچه جملات بررسی شده و اطمینان حاصل می‌شود که جملات متوالی کاملاً متمایز هستند.
    """
    total_quotes = len(CAFE_MOTIVATIONAL_QUOTES)
    recent_indices = set(await db.get_recent_quote_indices(limit=total_quotes - 5))
    available_indices = [i for i in range(total_quotes) if i not in recent_indices]
    
    if not available_indices:
        # اگر تقریباً تمام جملات یک دور کامل نمایش داده شدند، چرخه از نو مجاز می‌شود
        available_indices = list(range(total_quotes))
        
    chosen_idx = random.choice(available_indices)
    return chosen_idx, CAFE_MOTIVATIONAL_QUOTES[chosen_idx]

def format_cafe_quote_message(quote: str) -> str:
    return (
        "☕ <b>یادداشت صبحگاهی کافه دنگ</b> 🥐\n"
        "━━━━━━━━━━━━━━━━━━━\n"
        "☀️ <b>صبح بخیر رفیق!</b>\n\n"
        f"✨ <i>«{quote}»</i>\n\n"
        "امیدوارم فنجون امروزت پر از آرامش، لبخند و اتفاق‌های قشنگ و ناب باشه 🌸☕"
    )

async def broadcast_daily_quote(bot: Bot) -> int:
    """ارسال پیام صبحگاهی کافه‌ای به تمام کاربران عضو ربات بدون تکرار"""
    user_ids = await db.get_all_user_ids()
    if not user_ids:
        return 0

    quote_idx, quote = await get_daily_quote_unique()
    text = format_cafe_quote_message(quote)
    sent_count = 0

    today_str = datetime.now(TEHRAN_TZ).strftime("%Y-%m-%d")
    await db.log_sent_quote(quote_idx, today_str)

    for uid in user_ids:
        try:
            await bot.send_message(uid, text, parse_mode="HTML")
            sent_count += 1
            await asyncio.sleep(0.05)  # جلوگیری از محدودیت Flood تلگرام
        except Exception:
            pass

    logger.info(f"💌 یادداشت کافه‌ای ۹ صبح (شماره {quote_idx}) برای {sent_count} کاربر با موفقیت ارسال شد.")
    return sent_count

async def start_daily_quote_scheduler(bot: Bot):
    """حلقه زمان‌بندی روزانه جهت ارسال خودکار پیام در ساعت ۹:۰۰ صبح به وقت تهران"""
    logger.info("⏰ سرویس زمان‌بندی یادداشت‌های کافه‌ای ساعت ۹ صبح فعال شد.")
    while True:
        try:
            now = datetime.now(TEHRAN_TZ)
            target = now.replace(hour=9, minute=0, second=0, microsecond=0)
            if now >= target:
                target += timedelta(days=1)

            sleep_seconds = (target - now).total_seconds()
            logger.info(f"⏳ یادداشت کافه‌ای بعدی در ساعت ۰۹:۰۰ صبح ({sleep_seconds / 3600:.2f} ساعت دیگر) ارسال خواهد شد.")
            await asyncio.sleep(sleep_seconds)

            # ارسال پیام ساعت ۹ صبح
            await broadcast_daily_quote(bot)

            # ۶۰ ثانیه خواب جهت عبور از دقیقه ۰۰
            await asyncio.sleep(60)
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.error(f"خطا در زمان‌بندی یادداشت کافه‌ای: {e}")
            await asyncio.sleep(60)
